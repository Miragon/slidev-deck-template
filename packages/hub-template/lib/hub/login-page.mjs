// Renders the sign-in page for one language.
//
// Deliberately NOT a VitePress page: it must be readable without a session, and
// the site's /assets/ bundles carry every page's content, so the page is
// self-contained (inline styles, one small script) and only leans on the logo,
// which the edge gate lets through. It POSTs to /api/login and works without
// JavaScript; the script only carries ?to through and shows the error message
// after a failed attempt. `scripts/build-login-pages.mjs` writes the files at
// build time, so they are never checked in and never drift from the config.

