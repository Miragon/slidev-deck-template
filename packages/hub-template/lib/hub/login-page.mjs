const escapeHtml = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/** The sign-in page HTML for `lang` (the root language or the other one). */
export function renderLoginPage(rawConfig, lang, { logo = "/komet.svg" } = {}) {
    const config = resolveConfig(rawConfig);
    const t = TEXTS[lang];
    if (!t) throw new Error(`No sign-in texts for language ${JSON.stringify(lang)}`);
    const twin = lang === config.locale ? config.other : config.locale;
    const twinLogin = loginPath(config, twin);
    const title = escapeHtml(config.title);

    return `<!doctype html>
<!-- Generated by scripts/build-login-pages.mjs from hub.config.mjs. Do not edit. -->
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>${t.title} – ${title}</title>
${STYLE}
</head>
<body>
<main>
  <div class="brand">
    <img src="${escapeHtml(logo)}" alt="">
    <span>${title}</span>
  </div>
  <h1>${t.title}</h1>
  <p class="hint">${t.hint}</p>
  <p class="error" id="error">${t.error}</p>
  <form method="post" action="/api/login">
    <input type="hidden" name="to" id="to" value="${startPath(config, lang)}">
    <input type="hidden" name="lang" value="${lang}">
    <label for="user">${t.user}</label>
    <input id="user" name="user" autocomplete="username" autocapitalize="none" autofocus required>
    <label for="password">${t.password}</label>
    <input id="password" name="password" type="password" autocomplete="current-password" required>
    <button type="submit">${t.submit}</button>
  </form>
  <p class="lang"><a id="lang-switch" href="${twinLogin}">${TEXTS[twin].switchTo}</a></p>
</main>
<script>
  // Carry the originally requested page through the form, keep it across a
  // failed attempt, and mirror it onto the language switch. Only same-site
  // paths: the function checks again, this is just the client half.
  var params = new URLSearchParams(location.search);
  var to = params.get("to") || "";
  var sameSite = false;
  try { sameSite = to.charAt(0) === "/" && new URL(to, "https://x.invalid").origin === "https://x.invalid"; } catch (e) {}
  if (sameSite) {
    document.getElementById("to").value = to;
    document.getElementById("lang-switch").href = "${twinLogin}?to=" + encodeURIComponent(to);
  }
  if (params.get("error")) document.getElementById("error").classList.add("show");
</script>
</body>
</html>
`;
}
